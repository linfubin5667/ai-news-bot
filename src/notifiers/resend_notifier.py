"""
Email notification via the Resend HTTPS API.

Raw Gmail SMTP is unreliable from cloud and CI networks (Gmail drops
the connection at the AUTH step for many datacenter IP ranges), so this
notifier sends over HTTPS instead and works from GitHub Actions and
other hosted runners.

Setup:
  1. Create a free account at https://resend.com (use the address that
     should receive the digest; the default onboarding sender can only
     deliver to your own account address).
  2. Create an API key and set RESEND_API_KEY.
  3. Set EMAIL_TO to the recipient, and enable the method with
     NOTIFICATION_METHODS=resend.
  4. Optional: verify your own domain in Resend and set RESEND_FROM to
     an address on it to lift the own-address-only restriction.
"""
import os
from datetime import datetime
from typing import Optional

import requests

from ..logger import setup_logger


logger = setup_logger(__name__)

API_URL = "https://api.resend.com/emails"
DEFAULT_FROM = "AI News Bot <onboarding@resend.dev>"


class ResendNotifier:
    """Send the digest by email through Resend's HTTPS API"""

    def __init__(
        self,
        api_key: Optional[str] = None,
        email_to: Optional[str] = None,
        sender: Optional[str] = None,
    ):
        self.api_key = api_key or os.getenv("RESEND_API_KEY")
        self.email_to = email_to or os.getenv("EMAIL_TO")
        self.sender = sender or os.getenv("RESEND_FROM") or DEFAULT_FROM

        if not all([self.api_key, self.email_to]):
            logger.warning(
                "Resend notifier not fully configured. "
                "Required: RESEND_API_KEY, EMAIL_TO"
            )
        else:
            logger.info(
                f"ResendNotifier initialized (to: {self.email_to}, from: {self.sender})"
            )

    def send(self, content: str, subject: Optional[str] = None, language: str = "en") -> bool:
        """Send the digest email. Returns True on success."""
        if subject is None:
            today = datetime.now().strftime("%Y-%m-%d")
            lang_suffix = f" [{language.upper()}]" if language != "en" else ""
            subject = f"AI News Digest - {today}{lang_suffix}"

        if not all([self.api_key, self.email_to]):
            logger.error("Resend notifier is not fully configured. Skipping send.")
            return False

        payload = {
            "from": self.sender,
            "to": [self.email_to],
            "subject": subject,
            "text": content,
            "html": self._to_html(content, subject),
        }
        try:
            response = requests.post(
                API_URL,
                json=payload,
                headers={
                    "Authorization": f"Bearer {self.api_key}",
                    "Content-Type": "application/json",
                },
                timeout=30,
            )
        except requests.RequestException as e:
            logger.error(f"Resend request failed: {e}")
            return False

        if response.status_code in (200, 201):
            try:
                message_id = (response.json() or {}).get("id", "?")
            except ValueError:
                message_id = "?"
            logger.info(f"Email sent via Resend (id: {message_id})")
            return True

        logger.error(
            f"Resend API error {response.status_code}: {response.text[:300]}"
        )
        return False

    @staticmethod
    def _to_html(content: str, subject: str) -> str:
        """Render the markdown digest as a simple HTML email body."""
        try:
            import markdown

            body = markdown.markdown(
                content,
                extensions=["nl2br", "tables", "fenced_code", "sane_lists"],
            )
        except ImportError:
            import html

            body = html.escape(content).replace("\n", "<br>\n")
        return (
            "<!DOCTYPE html><html><head><meta charset=\"UTF-8\"></head>"
            f"<body><h1>{subject}</h1>{body}"
            "<hr><p>This email was automatically generated by AI News Bot</p>"
            "</body></html>"
        )
